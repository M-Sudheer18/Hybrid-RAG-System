from typing import List, Dict, Any, Optional, Generator
from groq import Groq
from config.settings import settings
from src.utils.helpers import time_it
from src.utils.logger import get_logger
logger = get_logger(__name__)

class GroqLLMClient:
    """Handles communication with the Groq API for RAG generation."""
    # Class Object
    _instance: Optional["GroqLLMClient"] = None
    # __new__() → creates the object
    # __init__() → initializes the object
    def __new__(cls):
        """Singleton pattern to maintain a single reusable Groq client connection pool."""
        if cls._instance is None:
            if not settings.GROQ_API_KEY:
                logger.error("GROQ_API_KEY is not set in environment or settings.")
                raise ValueError("GROQ_API_KEY must be configured before initializing GroqLLMClient.")
            logger.info("Initializing Groq Client..")
            cls._instance = super(GroqLLMClient, cls).__new__(cls)
            cls._instance.client = Groq(api_key=settings.GROQ_API_KEY)
            cls._instance.model_name = getattr(
                settings,
                "GROQ_MODEL_NAME",
                "openai/gpt-oss-120b"
            )
            logger.info(f"Groq client ready using model: [{cls._instance.model_name}]")
        return cls._instance

    @classmethod
    def get_instance(cls) -> "GroqLLMClient":
        return cls()  # Retrieves the Singleton instance

    @time_it
    def generate(
        self,
        messages: List[Dict[str, str]],
        temperature: float= getattr(settings, "TEMPERATURE", 0.1),
        max_tokens: int= getattr(settings, "MAX_TOKENS", 1024),
        reasoning_effort: str = "medium"
    ) -> str:
        """Executes a blocking completion request against the Groq API"""
        if not messages:
            raise ValueError("Messages can't be empty.")
        try:
            logger.debug(f"Dispatching completion request to {self.model_name} (temperature={temperature})...")
            response = self.client.chat.completions.create(
                model=self.model_name,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                stream=False,
                include_reasoning=False,
                reasoning_effort=reasoning_effort
            )
            content = response.choices[0].message.content or ""
            usage = response.usage
            if usage:
                logger.info(
                    f"Groq call completed | Prompt Tokens: {usage.prompt_tokens} | "
                    f"Completion Tokens: {usage.completion_tokens} | Total: {usage.total_tokens}"
                )
            return content.strip()
        except Exception as e:
            logger.error(f"Groq API completion call failed: {e}", exc_info=True)
            raise RuntimeError(f"Groq inference error: {e}")

    def generate_stream(
        self,
        messages: List[Dict[str, str]],
        temperature: float = getattr(settings, "TEMPERATURE", 0.1),
        max_tokens: int = getattr(settings, "MAX_TOKENS", 1024),
        reasoning_effort: str = "medium"
    ) -> Generator[str, None, None]:
        """
        Yields tokens incrementally as they are generated by Groq.
        Designed for FastAPI Server-Sent Events (SSE) and Streamlit st.write_stream.
        """
        if not messages:
            raise ValueError("Messages can't be empty.")
        try:
            logger.debug(f"Dispatching streaming completion request to {self.model_name}...")
            stream = self.client.chat.completions.create(
                model=self.model_name,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                stream=True,
                include_reasoning=False,
                reasoning_effort=reasoning_effort
            )
            for chunk in stream:
                delta_content = chunk.choices[0].delta.content
                if delta_content:
                    yield delta_content
        except Exception as e:
            logger.error(f"Groq streaming connection interrupted: {e}", exc_info=True)
            raise RuntimeError(f"Groq streaming error: {e}")

        
